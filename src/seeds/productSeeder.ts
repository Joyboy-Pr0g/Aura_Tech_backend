export async function seedProducts(): Promise<void> {
  const productRepo = AppDataSource.getRepository(Product);
  const variantRepo = AppDataSource.getRepository(ProductVariant);
  const categoryRepo = AppDataSource.getRepository(Category);
  const userRepo = AppDataSource.getRepository(User);

  const admin = await userRepo.findOne({ where: { role: Role.ADMIN } });
  if (!admin) {
    console.log('⚠️  Skipping products — no admin user found. Run user seeder first.');
    return;
  }

  let created = 0;
  let skipped = 0;

  for (let i = 0; i < products.length; i++) {
    const p = products[i];

    const existing = await productRepo.findOne({ where: { slug: p.slug } });
    if (existing) {
      skipped++;
      continue;
    }

    const category = await categoryRepo.findOne({ where: { slug: p.categorySlug } });
    if (!category) {
      console.log(`⚠️  Skipped product (category missing): ${p.title} → ${p.categorySlug}`);
      skipped++;
      continue;
    }

    const product = await productRepo.save(
      productRepo.create({
        slug: p.slug,
        title: p.title,
        description: p.description,
        price: p.price,
        brand: p.brand,
        category_id: category.id,
        stock_quantity: p.stock_quantity,
        features: p.features,
        created_by_id: admin.id,
        images: buildImages(i, p.useAllImages),
      }),
    );

    for (const v of p.variants ?? []) {
      await variantRepo.save(
        variantRepo.create({
          product_id: product.id,
          sku: v.sku,
          size: v.size,
          color: v.color,
          stock_quantity: v.stock_quantity,
          price: v.price ?? null,
        }),
      );
    }

    created++;
  }

  console.log(`✅ Products seed complete: ${created} created, ${skipped} skipped (${products.length} total in catalog).`);
}
