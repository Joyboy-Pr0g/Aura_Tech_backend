function buildImages(index: number, useAll = false): ProductImage[] {
  if (useAll) {
    return SEED_IMAGES.map((image, i) => ({ ...image, is_primary: i === 0 }));
  }

  const primaryIdx = index % SEED_IMAGES.length;
  const secondaryIdx = (index + 1) % SEED_IMAGES.length;

  const images: ProductImage[] = [
    { ...SEED_IMAGES[primaryIdx], is_primary: true },
  ];

  if (secondaryIdx !== primaryIdx) {
    images.push({ ...SEED_IMAGES[secondaryIdx], is_primary: false });
  }

  return images;
}

