function labelField(field: string): string {
  return FIELD_LABELS[field] ?? field;
}

function translateValidation(message: string): string {
  const required = message.match(/^"(.+)" is required$/);
  if (required) return `"${labelField(required[1])}" مطلوب`;

  const notAllowed = message.match(/^"(.+)" is not allowed$/);
  if (notAllowed) return `"${labelField(notAllowed[1])}" غير مسموح`;

  const mustBe = message.match(/^"(.+)" must be (.+)$/);
  if (mustBe) return `"${labelField(mustBe[1])}" يجب أن يكون ${mustBe[2]}`;

  const length = message.match(/^"(.+)" length must be (.+)$/);
  if (length) return `طول "${labelField(length[1])}" يجب أن يكون ${length[2]}`;

  return message;
}

export function translateMessage(message: string): string {
  if (!message) return message;
  if (EXACT[message]) return EXACT[message];

  if (message.includes('; ')) {
    return message.split('; ').map((part) => translateMessage(part.trim())).join('؛ ');
  }

  const onlyUnits = message.match(/^Only (\d+) units available$/);
  if (onlyUnits) return `يتوفر ${onlyUnits[1]} وحدة فقط`;

  const orderStatus = message.match(/^Order is (.+), cannot submit payment$/);
  if (orderStatus) return `حالة الطلب ${orderStatus[1]}، لا يمكن إرسال الدفع`;

  const paymentStatus = message.match(/^Payment is already (.+)$/);
  if (paymentStatus) return `الدفع ${paymentStatus[1]} بالفعل`;

  const cannotTransition = message.match(/^Cannot transition from (.+) to (.+)$/);
  if (cannotTransition) return `لا يمكن الانتقال من ${cannotTransition[1]} إلى ${cannotTransition[2]}`;

  if (message.startsWith('"') || message.includes(' is ')) {
    return translateValidation(message);
  }

  return message;
}
